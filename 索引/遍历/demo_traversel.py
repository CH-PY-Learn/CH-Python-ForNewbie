# 序列遍历：展示通过索引下标访问与 for 循环遍历容器

name_in_class = [
    "张伟", "王芳", "李娜", "刘洋", "陈杰",
    "杨兵", "赵敏", "黄超", "周丽", "吴强",
    "徐静", "孙涛", "胡磊", "朱婷", "高飞",
    "林健", "何霞", "郭栋", "马莉", "罗亮",
    "梁博", "宋茜", "郑凯", "谢宇", "韩梅",
    "唐平", "冯刚", "于洋", "董欣", "萧毅"
]

# ==================== 1. 索引下标访问元素 ====================

print(name_in_class[0])  # 第 0+1 个数据
print(name_in_class[1])  # 第 1+1 个数据


# ==================== 2. for 循环顺序遍历容器 ====================

for i in name_in_class:
    print(i)  # 逐个把数据打印到终端上

# 通过观察终端的内容可以发现打印的内容顺序与数据中存放的顺序一一对应。

