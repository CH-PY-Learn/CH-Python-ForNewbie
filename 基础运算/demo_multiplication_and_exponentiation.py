# 乘法与幂运算

# ==================== 1. 乘法运算（*）：表示倍数相加 ====================

n = 6
x = 2

print(n * x)  # 等价于 x + x + x + x + x + x


# ==================== 2. 幂运算（**）：表示乘方相乘 ====================

n = 5
x = 10
print(n ** x)  # 等价于 10 个 5 相乘

