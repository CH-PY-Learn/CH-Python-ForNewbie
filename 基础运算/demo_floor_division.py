# 地板除运算：展示 // 向下取整与返回类型特性

# ==================== 1. 地板除（//）基本运算 ====================

# 对于两个数字之间除法如果需要得到一个整数值可以使用地板除 //
# 地板除表示进行运算后，对其进行“向下取整”，向下取整表示向数轴的左边靠拢直到遇见一个整数值
# 举例一个除法的结果为 3.2 地板除会将答案更新为3，无论2为10进制中任意数字答案都为3

test_number1 = 99
test_number2 = 35
test_number3 = 33.0

print(test_number1 // test_number2)


# ==================== 2. 地板除类型特性与浮点数参与 ====================

"""
针对一个数字想要不通过type(表达式)检查该变量类型
可以通过print(表达式)来查看是否存在小数点，若有，一般为浮点数，反之为整数

对于地板除//，只有当除数与被除数的表达式均为整数，返回值也为整数，反之为浮点数
"""

print(test_number1 // test_number3)  # 尽管能整除，但 33.0 为浮点数，结果也是浮点数

