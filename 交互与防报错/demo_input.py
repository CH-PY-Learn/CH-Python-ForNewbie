# input 输入交互：展示用户输入、类型转换与嵌套处理

# ==================== 1. input() 基础用法与接收字符串 ====================

# input()：接收用户键盘输入的内容，返回值始终为字符串（str）类型

user_name = input("请输入您的姓名：")
print("你好，" + user_name + "！")
# 用户输入的姓名被保存到 user_name 变量中

city = input("请输入您所在的城市：")
print(f"欢迎来自 {city} 的朋友！")
# 结合 f-string 格式化输出用户输入的内容


# ==================== 2. input() 输入数值与类型转换 ====================

# 输入数值时的类型转换：需使用 int() 或 float() 将字符串转为数字

age_str = input("请输入您的年龄：")
age = int(age_str)

if age >= 18:
    print("您已达到法定成年年龄")
else:
    print("您尚未成年")
# 将输入的年龄字符串转为整数后进行大小比较


# ==================== 3. 嵌套写法：直接转换 input() 返回值 ====================

price = float(input("请输入商品单价（元）："))
quantity = int(input("请输入购买数量（件）："))

total_cost = price * quantity
print("订单总金额为：", total_cost, "元")

