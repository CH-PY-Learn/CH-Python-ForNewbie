# 条件判断与比较运算：展示 if, elif, else 条件分支

# ==================== 1. 单分支 if 条件判断（相等 == 与不等 !=） ====================

my_planet = "earth"

if my_planet == "earth":
    print("我是地球人")
# 当 my_planet 的值为 "earth" 时，执行 if 代码块

if my_planet != "moon":
    print("我不生活在月球上")
# != 表示“不等于”，当 my_planet 不等于 "moon" 时，执行 if 代码块


# ==================== 2. if-else 双分支条件判断 ====================

name = "小明"

if name != "小明":
    ...
else:
    print("我的名字叫做小明")
# 当 if 条件不成立时，执行 else 的代码块


# ==================== 3. if-elif-else 多分支条件判断 ====================

grade = 80

if grade >= 80:
    print("优秀")

elif grade >= 60:
    print("及格")

else:
    print("不及格")

