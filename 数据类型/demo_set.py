# set：集合可变类型、无序性与修改方法

# ==================== 1. 集合定义与无序性 ====================

ids = {"001", "002", "003", "004", "005", "006", "007"}

print(ids)
# 通过打印出的数据发现内容顺序不会和代码放进去的顺序一致
# 这称为“无序”，这种数据都无法直接用索引读取内容


# ==================== 2. 集合常用修改方法（add 等） ====================

# 对于一个集合，它有以下基础方法来改变集合

"""
add
remove
discard
"""
# 只需要在集合或指向集合的表达式之后加一个：".方法"即可使用

ids.add("008")
print(ids)
# 元素增加了

