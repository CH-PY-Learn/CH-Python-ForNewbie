# list：列表可变类型、解包与修改方法

# ==================== 1. 列表定义与元素输出 ====================

scores_for_class_a = [60, 60, 60, 60, 65, 90]
scores_for_class_b = [90, 65, 60, 60, 60, 60]

print(scores_for_class_a)
print(scores_for_class_b)


# ==================== 2. 列表解包运算（*） ====================

# 针对列表，Python 有一个方法叫做“解包”，只需要在列表或指向列表的表达式前面加一个星号 *
# 目的是把列表每一个元素拆分成单独的元素，这样元素就不在列表内了

print(*scores_for_class_a)
print(*scores_for_class_b)


# ==================== 3. 列表常用修改方法（append 等） ====================

simple_list = []
# 对于一个列表，它有以下基础方法来改变列表

"""
append 针对列表末尾增加
insert 针对指定元素增加
remove 针对指定元素减少
sort 从元素小到大的的数据排序 （不止数字可以被排序）
pop 针对指定索引减少
"""
# 只需要在列表或指向列表的表达式之后加一个：".方法"即可使用

print(simple_list)
simple_list.append('apple')
print(simple_list)
# 元素增加了

