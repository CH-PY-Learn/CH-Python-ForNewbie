# int：整数类型存储与转换

# ==================== 1. 整数直接定义与 int() 转换 ====================

age = 18
grade = int(60)

# 在 int() 括号中的内容只要是一个整数就会被转译为整数，int() 会自动过滤空字符如换行符和空格
direction = int("180\n")

print(age)
print(grade)
print(direction)

