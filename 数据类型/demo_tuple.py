# tuple：元组不可变类型、多元赋值与解包

# ==================== 1. 元组定义、多元赋值与解包输出 ====================

time = (60, 60, 24)  # 以此代表 60 秒为 1 分钟，60 分钟为 1 小时，24 小时为 1 天

date = 22, 1, 10  # 也可以用于储存生日

print(time)
print(date)
print(*date, sep='-')  # 解包也可以用于元组

