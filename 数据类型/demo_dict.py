# dict：字典键值对存储与修改

# ==================== 1. 字典定义与键值对存储 ====================

people_love_food = {
    "小明": "apple",
    "小美": "banana",
    "小豪": "orange",
}

print(people_love_food)


# ==================== 2. 字典修改与删除操作 ====================

# 对于一个字典，它有以下基础方法来改变字典

"""
del # 删除键所在的键值对 （无返回值）
pop 删除键所对在的键值对 （有返回值）
update 用于覆盖字典
"""

del people_love_food["小明"]
print(people_love_food)
