# 容器常用的通用操作：展示 count, index, len, in, reversed 与 clear

# 通用操作可对一般的容器进行操作，本文件只展示 md 文件中提到的常用操作

from_one_to_hundred = """
12345678910111213141516171819202122232425262728293031323334353637383
94041424344454647484950515253545556575859606162636465666768697071727
37475767778798081828384858687888990919293949596979899100
"""

# ==================== 1. count：统计元素出现次数 ====================

one_count = from_one_to_hundred.count("1")  # count 方法，返回容器中指定元素的个数。
print(one_count)


# ==================== 2. index 与 len：查找索引与获取长度 ====================

names = ["小明", "小红", "小刚"]

names.index("小红")  # index 方法，返回容器中指定元素的索引。
print(names.index("小红"))

length_names = len(names)  # len 函数，返回容器的长度。
print(length_names)


# ==================== 3. in 成员检测运算符 ====================

if "小明" in names:  # in 运算符，判断容器中是否包含指定元素。
    print("小明在names列表中")


# ==================== 4. reversed 与 clear：逆序与清空 ====================

names = list(reversed(names))  # reversed 函数，返回容器的逆序。
print(names)

names.clear()  # clear 方法，清空容器中的所有元素。
print(names)

