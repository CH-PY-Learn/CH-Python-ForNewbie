# 循环控制：展示 for 循环、while 循环以及 break 打断机制

# ==================== 1. for 循环与 range 遍历 ====================

for i in range(10):
    print(f"这是第{i}次循环")


# ==================== 2. while 循环与条件判断 ====================

# while 循环实际上是将冒号前的内容当作布尔值判断，如果是 True 则执行，反之结束循环

while True:
    print("如果没有下一行代码，这是死循环")
    break


# ==================== 3. 嵌套 while 循环与 break 作用域 ====================

counter = 0
while counter < 3:
    while True:
        print("这段循环会被不断执行，但紧接着又被打断")
        counter += 1
        break

# break 只能打断当前缩进所对应的循环
