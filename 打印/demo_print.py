# print 函数：将内容打印输出到终端

# ==================== 1. 基础打印与表达式计算 ====================

print("Hello World!")
# 打印双引号内的内容，包括标点符号和空格，但不包括双引号自身

print(1 + 1)  # python 表达式，打印 2

a = 1  # 定义变量 a
print(a)  # a 作为一个表达式，Python 解读后输出其值


# ==================== 2. 逗号多参数打印与默认空格分隔 ====================

print("Hello", "World!")
print("Hello", "World!")
# 逗号被视为参数间隔，默认为 1 个空格；括号内非引号内的空格被忽略


# ==================== 3. 自定义分隔符 sep 与结束符 end ====================

print("我的名字", "小明", sep="叫做")  # sep 间隔指定为：“叫做”
print("我的名字叫做", end="小明。")  # end 指定结束字符为：“小明。”
print('修改上一行print的end参数为"小明"后，没有了默认的换行符，这一行会紧紧贴着上一行的内容')


# ==================== 4. f-string 格式化输出 ====================

print(f"{1 + 1} {a} 我是小明")  # 花括号内包裹表达式，Python 会先计算再输出

